import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";

const { PGlite } = await import(process.env.FORJA_PGLITE_MODULE || "@electric-sql/pglite");
const db = new PGlite();
const aplicar = (ruta) => db.exec(readFileSync(new URL(ruta, import.meta.url), "utf8"));
const migrar = (archivo) => aplicar(`../supabase/migrations/${archivo}.sql`);
const elegir = async (sql, valores = []) => (await db.query(sql, valores)).rows[0];
const como = async (id) => {
  await db.exec("reset role");
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
  await db.exec("set role authenticated");
};
const [gm, jugador, otro, pendiente] = Array.from({ length: 4 }, () => randomUUID());

try {
  for (const archivo of ["forja_copias_schema", "creacion_schema"]) {
    await aplicar(`./fixtures/${archivo}.sql`);
  }
  for (const archivo of [
    "20261030_forja_copias",
    "20261030_forja_tipos_y_dados",
    "20261030_combate_pasivas",
    "20261030190047_pasivas_reactivas_y_elementos",
  ]) {
    await migrar(archivo);
  }
  await db.exec(`
    create role service_role;
    create table auth.users(id uuid primary key,email text);
    grant usage on schema auth to authenticated;
    grant execute on function auth.uid() to authenticated;
    alter table perfiles add column email text, add column estado text default 'aprobado',
      add column lugares_conocidos text[];
    alter table perfiles enable row level security;
    grant select,update on perfiles to authenticated;
    grant select,insert,update,delete on inventario_jugador,personajes to authenticated;
    alter table forja_maestra add column requisitos text,add column defectos text,add column historia text,
      add column nivel integer default 1,add column nivel_maximo integer default 20;
    alter table inventario_jugador add column created_at timestamptz default now();
    alter table personajes alter column id add generated by default as identity;
    alter table personajes add column atributos jsonb default '{}',add column estado_vida text default 'vivo',
      add column historia text,add column raza text,add column defecto text,add column lugar_reencarnacion text,
      add column nivel int default 1,add column exp_total bigint default 0,
      add column elecciones_pendientes int default 0,add column habilidades_elegidas jsonb default '[]';
    alter table config_estadisticas add column limite_jugador numeric;
    alter table categorias_forja add column raza_unica_de uuid references perfiles(id);
    create function public.forja_linaje_claves(p text) returns text[] language sql stable set search_path=public as $$
      with recursive c as (
        select * from public.categorias_forja where clave=p union all
        select x.* from public.categorias_forja x join c on c.parent_id=x.id
      ) select array_agg(clave) from c
    $$;
  `);
  for (const archivo of [
    "20261103173113_forja_motor_reglas",
    "20261103174011_tienda_negociacion_privada",
    "20261103175054_monedas_y_tienda_almas",
    "20261103182719_equipo_en_combate",
    "20261103183117_tienda_almas_solo_personajes",
    "20261104004039_reencarnados_combate_alma",
    "20261104005416_inventario_visual_consumibles",
    "20261107191921_tienda_propuestas_cancelacion",
    "20261107192533_personajes_vida_cementerio",
    "20261107193447_personajes_alma_al_morir",
    "20261107201357_alma_cuenta_baul",
    "20261107203258_arbol_habilidades_individual",
    "20261107210338_party_companeros_experiencia",
  ]) {
    await migrar(archivo);
  }
  for (const id of [gm, jugador, otro, pendiente]) {
    await db.query("insert into auth.users(id) values($1)", [id]);
  }
  await db.query(`
    insert into perfiles(id,rol,estado) values
      ($1,'KUROI','aprobado'),($2,'REENCARNADO','aprobado'),
      ($3,'REENCARNADO','aprobado'),($4,'REENCARNADO','pendiente')
  `, [gm, jugador, otro, pendiente]);
  const plantilla = async (nombre, ligada) => (await elegir(`
    insert into forja_maestra(nombre,tipo,tipo_creacion,ligado_al_alma,stats)
    values($1,'humanos','personaje',$2,'{"vida":20,"ph":5}') returning id
  `, [nombre, ligada])).id;
  const personaje = await plantilla("Personaje de prueba", false);
  const ligada = await plantilla("Creación única", true);
  const moneda = (await elegir("select id from monedas where simbolo='ORO'")).id;
  const operacion = (accion, { id = null, destino = null, propuesta = null, forja = personaje, tienda = "almas" } = {}) =>
    elegir("select tienda_operar_v4($1,$2,$3,'Oferta de prueba',$4,'monedas',$5,10,$6,$7) as id",
      [accion, id, forja, tienda, moneda, propuesta, destino]);
  const entregar = (usuario, destino, solicitud = randomUUID()) =>
    elegir("select personaje_entregar($1,$2,$3,$4) as id", [usuario, personaje, destino, solicitud]);
  const saldo = async () => (await elegir(
    "select cantidad::int as cantidad from saldos_usuario where user_id=$1 and moneda_id=$2", [jugador, moneda],
  )).cantidad;
  const mostrarOferta = (id) => elegir(
    "select estado,destino_personaje,propuesta from tienda_ofertas where id=$1", [id],
  );
  const compra = (id) => elegir(
    "select id,es_companero,party_activo,raza from personajes where compra_oferta_id=$1", [id],
  );

  await como(gm);
  await db.query("select monedas_gestionar('ajustar',$1,$2,40,null,null,'Prueba',$3)", [jugador, moneda, randomUUID()]);
  const legado = (await elegir(
    "select tienda_operar_v3('publicar',p_forja=>$1,p_descripcion=>'Oferta anterior',p_tienda=>'almas') as id", [personaje],
  )).id;

  await db.exec("reset role");
  await migrar("20261121120100_personajes_cuerpos_tienda_almas");
  await como(gm);
  const primero = (await operacion("publicar")).id;
  const segundo = (await operacion("publicar")).id;
  const unico = (await operacion("publicar", { forja: ligada })).id;

  await como(pendiente);
  assert.equal(await mostrarOferta(primero), undefined);
  await assert.rejects(operacion("negociar", { id: primero, destino: "npc" }), /no tiene acceso/);

  await como(jugador);
  assert.equal((await mostrarOferta(primero)).estado, "disponible");
  await assert.rejects(entregar(jugador, "cuerpo"), /Solo Kuroi/);
  await assert.rejects(operacion("negociar", { id: unico, destino: "cuerpo" }), /no admite/);
  await operacion("negociar", { id: primero, destino: "cuerpo", propuesta: "Primer cuerpo" });
  await operacion("negociar", { id: segundo, destino: "cuerpo" });
  assert.equal(await saldo(), 40);
  await como(otro);
  assert.equal(await mostrarOferta(primero), undefined);
  await assert.rejects(operacion("proponer", { id: primero, destino: "npc" }), /propia negociación/);

  await como(gm);
  await operacion("aceptar", { id: primero });
  assert.deepEqual(await compra(primero), { id: 1, es_companero: false, party_activo: false, raza: "humanos" });
  assert.equal(await saldo(), 30);
  await assert.rejects(operacion("aceptar", { id: segundo }), /ya tiene un cuerpo/);
  assert.equal(await saldo(), 30);
  assert.equal(await compra(segundo), undefined);
  assert.equal((await mostrarOferta(segundo)).estado, "negociando");

  await como(jugador);
  await operacion("proponer", { id: segundo, destino: "npc", propuesta: "Ahora como NPC" });
  await assert.rejects(operacion("negociar", { id: legado, destino: "cuerpo" }), /ya tiene un cuerpo/);
  await como(gm);
  assert.equal((await mostrarOferta(segundo)).destino_personaje, "npc");
  await operacion("aceptar", { id: segundo });
  const npc = await compra(segundo);
  assert.equal(npc.es_companero, true);
  assert.equal(npc.party_activo, true);
  assert.equal((await elegir("select activo from party_companeros where personaje_id=$1", [npc.id])).activo, true);
  assert.equal(await saldo(), 20);
  await assert.rejects(operacion("aceptar", { id: segundo }), /ya está resuelta/);

  await como(jugador);
  await operacion("negociar", { id: legado, destino: "npc", propuesta: "Privado" });
  await operacion("cancelar", { id: legado });
  await como(otro);
  assert.deepEqual(await mostrarOferta(legado), { estado: "disponible", destino_personaje: null, propuesta: null });
  await operacion("negociar", { id: legado, destino: "npc" });
  await como(gm);
  await operacion("rechazar", { id: legado });
  assert.deepEqual(await mostrarOferta(legado), { estado: "disponible", destino_personaje: null, propuesta: null });

  const solicitud = randomUUID();
  const directo = await entregar(otro, "npc", solicitud);
  assert.deepEqual(await entregar(otro, "npc", solicitud), directo);
  await assert.rejects(entregar(otro, "cuerpo", solicitud), /otra entrega/);
  await db.exec("reset role");
  await db.query("insert into personajes(user_id,nombre,estado_aprobacion) values($1,'En revisión','pendiente')", [otro]);
  await como(gm);
  await assert.rejects(entregar(otro, "cuerpo"), /solicitud activa/);
  await db.query("update personajes set estado_aprobacion='rechazado' where nombre='En revisión'");
  assert.ok((await entregar(otro, "cuerpo")).id, "Un NPC y una ficha rechazada no consumen el cupo");
  await assert.rejects(entregar(otro, "cuerpo"), /ya tiene un cuerpo/);
  await db.query("update perfiles set mente_colmena=true where id=$1", [otro]);
  assert.ok((await entregar(otro, "cuerpo")).id, "Mente colmena permite un segundo cuerpo");

  await como(jugador);
  await operacion("negociar", { id: unico });
  await como(gm);
  await operacion("aceptar", { id: unico });
  assert.equal(await compra(unico), undefined);
  assert.equal((await elegir("select personaje_id from inventario_jugador where compra_oferta_id=$1", [unico])).personaje_id, null);

  await db.query("update personajes set estado_vida='muerto' where compra_oferta_id=$1", [primero]);
  await como(jugador);
  await db.query("select tienda_operar_v3('negociar',p_id=>$1,p_tienda=>'almas')", [legado]);
  await como(gm);
  await operacion("aceptar", { id: legado });
  assert.equal((await compra(legado)).es_companero, false);

  const anterior = (await elegir("select party_asignar($1,p_forja=>$2) as id", [otro, personaje])).id;
  await db.query("select party_retirar($1)", [anterior]);
  assert.equal((await elegir("select party_asignar($1,p_personaje=>$2) as id", [jugador, anterior])).id, anterior);
  assert.equal((await elegir("select user_id from party_companeros where personaje_id=$1", [anterior])).user_id, jugador);

  await db.exec("reset role");
  await db.query("update categorias_forja set raza_unica_de=$1 where clave='humanos'", [jugador]);
  await como(gm);
  await assert.rejects(entregar(otro, "cuerpo"), /Esa raza única pertenece a otro reencarnado/);

  console.log("Tienda de Almas y entregas GM: compra por destino, cupo, cobro atómico, privacidad y Baúl del Alma.");
} finally {
  await db.close();
}
